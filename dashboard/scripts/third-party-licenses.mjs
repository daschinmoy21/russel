// Write dist/THIRD-PARTY-LICENSES.txt: every npm package in the production
// dependency closure of package.json, with its license and license text.
//
// The dashboard's JavaScript is first-party; Astro generates the HTML and the
// module wrappers. Listing the whole runtime closure (not only what ended up
// in dist/) is a superset of anything that can contribute code to the bundle,
// so the release tarball carries the notices MIT/BSD/ISC/Apache require.
//
// Runs after `astro build` (see package.json "build"). Fails if a package in
// the closure is not installed or has neither a license field nor a file.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "dist", "THIRD-PARTY-LICENSES.txt");

function readJson(path) {
	return JSON.parse(readFileSync(path, "utf8"));
}

// Node resolution: nearest node_modules/<name> walking up from `from`.
function resolvePackage(name, from) {
	let dir = from;
	for (;;) {
		const candidate = join(dir, "node_modules", name);
		if (existsSync(join(candidate, "package.json"))) return candidate;
		if (dir === root) return null;
		const parent = dirname(dir);
		if (parent === dir) return null;
		dir = parent;
	}
}

function licenseOf(pkg) {
	if (typeof pkg.license === "string") return pkg.license;
	if (pkg.license && typeof pkg.license.type === "string") return pkg.license.type;
	if (Array.isArray(pkg.licenses)) {
		const types = pkg.licenses.map((l) => l && l.type).filter(Boolean);
		if (types.length) return types.join(" OR ");
	}
	return null;
}

function licenseTexts(dir) {
	return readdirSync(dir, { withFileTypes: true })
		.filter((d) => d.isFile() && /^(licen[cs]e|copying|notice)([-_.].*)?$/i.test(d.name))
		.map((d) => d.name)
		.sort()
		.map((f) => ({ file: f, text: readFileSync(join(dir, f), "utf8").trim() }));
}

// Packages that ship no license file. Each maps to committed text from a
// verified source (the upstream repo's license file, or SPDX text plus the
// package's author); scripts/license-fallbacks/*.txt records which. Any other
// package without a license file fails the build.
const FALLBACKS = [
	[/^@esbuild\//, "esbuild"],
	[/^@rollup\/rollup-/, "rollup"],
	[/^@img\/sharp-libvips-/, "sharp-libvips"],
	[/^boolbase$/, "boolbase"],
	[/^dlv$/, "dlv"],
	[/^piccolore$/, "piccolore"],
	[/^retext(-latin|-stringify)?$/, "retext"],
];

function fallbackTexts(name) {
	const hit = FALLBACKS.find(([re]) => re.test(name));
	if (!hit) return [];
	const file = `scripts/license-fallbacks/${hit[1]}.txt`;
	return [{ file, text: readFileSync(join(root, file), "utf8").trim() }];
}

const rootPkg = readJson(join(root, "package.json"));
const seen = new Map(); // dir -> entry
const queue = Object.keys(rootPkg.dependencies ?? {}).map((name) => ({
	name,
	from: root,
	optional: false,
}));

while (queue.length) {
	const { name, from, optional } = queue.shift();
	const dir = resolvePackage(name, from);
	if (!dir) {
		// Platform-specific optional deps (esbuild, sharp, rollup binaries) are
		// only installed on matching hosts.
		if (optional) continue;
		throw new Error(`${name} (needed by ${from}) is not installed; run bun install`);
	}
	if (seen.has(dir)) continue;
	const pkg = readJson(join(dir, "package.json"));
	let texts = licenseTexts(dir);
	if (texts.length === 0) texts = fallbackTexts(pkg.name);
	if (texts.length === 0) {
		throw new Error(
			`${pkg.name}@${pkg.version} ships no license file: add verified text under ` +
				"scripts/license-fallbacks/ and map it in FALLBACKS",
		);
	}
	const license = licenseOf(pkg) ?? "see license text";
	seen.set(dir, { name: pkg.name, version: pkg.version, license, texts });
	for (const dep of Object.keys(pkg.dependencies ?? {})) {
		queue.push({ name: dep, from: dir, optional: false });
	}
	for (const dep of Object.keys(pkg.optionalDependencies ?? {})) {
		queue.push({ name: dep, from: dir, optional: true });
	}
}

const entries = [...seen.values()].sort(
	(a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
);

const lines = [
	"Russel dashboard: third-party licenses",
	"",
	"The dashboard is Apache-2.0 (see LICENSE and NOTICE in the Russel release).",
	"Its JavaScript is first-party; the HTML and module wrappers are generated by",
	"Astro. This file lists every npm package in the dashboard's production",
	`dependency closure (${entries.length} packages) with its license text. That is a`,
	"superset of anything that can contribute code to this bundle: most entries",
	"are build tooling (compiler, bundler, image processing) that does not ship.",
	"",
	"The Inter and JetBrains Mono fonts are not bundled: the browser loads them",
	"from Google Fonts at runtime (SIL Open Font License 1.1).",
	"",
	"Summary",
	"-------",
	...entries.map((e) => `${e.name}@${e.version}  ${e.license}`),
	"",
];
for (const e of entries) {
	lines.push("=".repeat(78), `${e.name}@${e.version}`, `License: ${e.license}`, "");
	for (const t of e.texts) {
		lines.push(`--- ${t.file}`, t.text, "");
	}
}

if (!existsSync(join(root, "dist"))) {
	throw new Error("dist/ does not exist; run astro build first");
}
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out} (${entries.length} packages)`);

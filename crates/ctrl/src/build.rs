    #[test]
    fn package_auto_flake_takes_precedence_over_detection() {
        // Committed flake.nix wins over package (AlreadyExists path).
        // Package wins over Cargo.toml / go.mod / static detection.
        // ensure_flake_exists needs the cached Nix system triple; tests never
        // call init_current_system (it shells out to nix), so seed it once.
        let _ = CURRENT_SYSTEM.set("x86_64-linux".to_string());
        with_nix_restricted_env(None, || {
            let rt = tokio::runtime::Builder::new_current_thread()
                .enable_all()
                .build()
                .expect("runtime");
            rt.block_on(async {
                let builder = NixBuilder;

                let committed = tempfile::tempdir().expect("tempdir");
                std::fs::write(committed.path().join("flake.nix"), "{}\n").unwrap();
                let generated = builder
                    .ensure_flake_exists(committed.path(), Some("navidrome"))
                    .await
                    .expect("committed flake must win");
                assert!(!generated);

                let dir = tempfile::tempdir().expect("tempdir");
                std::fs::write(dir.path().join("Cargo.toml"), "[package]\n").unwrap();
                let generated = builder
                    .ensure_flake_exists(dir.path(), Some("navidrome"))
                    .await
                    .expect("package auto-flake");
                assert!(generated);
                let content =
                    std::fs::read_to_string(dir.path().join("flake.nix")).expect("flake written");
                assert!(content.starts_with(NixBuilder::GENERATED_MARKER));
                assert!(content.contains("pkgs.navidrome"));
                assert!(!content.contains("buildRustPackage"));
            });
        });

        // Restricted mode refuses package auto-generation too.
        // Must not nest block_on on the same runtime (deadlocks).
        with_nix_restricted_env(Some("1"), || {
            let rt = tokio::runtime::Builder::new_current_thread()
                .enable_all()
                .build()
                .expect("runtime");
            rt.block_on(async {
                let builder = NixBuilder;
                let dir = tempfile::tempdir().expect("tempdir");
                let err = builder
                    .ensure_flake_exists(dir.path(), Some("navidrome"))
                    .await
                    .expect_err("restricted mode must refuse package auto-flake");
                assert!(err.to_string().contains("RUSSEL_NIX_RESTRICTED"));
            });
        });
    }
